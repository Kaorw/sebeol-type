/** 출처 표기 문구 */
export function creditOf(item: TextItem): string {
  if (item.kind === '문학' && item.src) return `${item.src.author} 「${item.src.title}」(${item.src.year})${item.src.modernized ? ' · 현대 표기' : ''}`;
  if (item.kind === '속담') return '전래 속담';
  return '신세벌 타자 창작 문장';
}
